/*
 * Real-Time Song Analyzer -- ECE243 Final Project
 *
 * Runs on the Nios V processor on a DE1-SoC board. Captures audio from
 * the WM8731 line-in at 8 kHz, runs a 1024-point Q15 fixed-point FFT
 * each frame, and displays results in real time.
 *
 * Analysis: RMS energy, bass/mid/treble band levels, beat detection,
 *           BPM (60-200), and mood classification (INTENSE/GROOVY/CHILL).
 *
 * Display modes (keys 1-4):
 *   1 - Spectrum: 32 FFT bars with peak-hold, beat flash border
 *   2 - Bar graph: large bass / mid / treble meters
 *   3 - Waveform: oscilloscope view, mood-tinted color
 *   4 - Mood screen: color wash + floating particles + stats overlay
 *
 * Other controls: Space = pause, R = reset, Up/Down = beat sensitivity.
 * HEX displays show BPM (HEX5-3) and energy (HEX2-0); LEDs show energy.
 * SW0 enables test mode; SW1/SW2 select the synthetic test signal.
 */

