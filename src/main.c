/* FFT Functions */

/*
 * In-place 1024-point radix-2 Cooley-Tukey FFT using Q15 fixed-point.
 * Input is DC-blocked, automatically down-scaled, and Hann-windowed.
 * Result is left in fft_real[] and fft_imag[].
 */
void fft_compute(int *samples) {
  int i, stage, group, k;
  int half_size, size, tw_step, tw_idx;
  int twiddle_r, twiddle_i, even_r, even_i;
  int dc_offset = compute_dc_offset(samples, FFT_SIZE);
  int input_shift = compute_auto_shift(samples, FFT_SIZE, dc_offset,
                                       FFT_TARGET_PEAK);

  /* Bit-reversal permutation: load conditioned samples into FFT arrays */
  for (i = 0; i < FFT_SIZE; i++) {
    int centered = (samples[i] - dc_offset) >> input_shift;
    fft_real[bit_rev[i]] = Q15_MUL(window_q15[i], centered);
    fft_imag[bit_rev[i]] = 0;
  }

  /* 10 stages of butterfly operations */
  half_size = 1;
  for (stage = 0; stage < FFT_LOG2; stage++) {
    size = half_size << 1;
    tw_step = FFT_HALF / half_size;

    for (group = 0; group < FFT_SIZE; group += size) {
      for (k = 0; k < half_size; k++) {
        tw_idx = k * tw_step;
        int odd_r = fft_real[group + k + half_size];
        int odd_i = fft_imag[group + k + half_size];

        /* Multiply the odd element by the twiddle factor W = cos - j*sin */
        twiddle_r = Q15_MUL(twiddle_cos[tw_idx], odd_r) -
                    Q15_MUL(twiddle_sin[tw_idx], odd_i);
        twiddle_i = Q15_MUL(twiddle_cos[tw_idx], odd_i) +
                    Q15_MUL(twiddle_sin[tw_idx], odd_r);

        /* Butterfly */
        even_r = fft_real[group + k];
        even_i = fft_imag[group + k];
        fft_real[group + k] = even_r + twiddle_r;
        fft_imag[group + k] = even_i + twiddle_i;
        fft_real[group + k + half_size] = even_r - twiddle_r;
        fft_imag[group + k + half_size] = even_i - twiddle_i;
      }
    }
    half_size = size;
  }
}

/* Compute magnitude of each FFT bin: |X[k]| = sqrt(re^2 + im^2) */
void fft_magnitudes(void) {
  fft_mag[0] = 0; /* suppress any residual DC after conditioning */
  for (int k = 1; k < FFT_HALF; k++) {
    long long r = fft_real[k];
    long long im = fft_imag[k];
    unsigned long long mag_sq =
        (unsigned long long)(r * r) + (unsigned long long)(im * im);
    fft_mag[k] = (int)isqrt_u64(mag_sq);
  }
}

/*
 * Extract bass, mid, and treble energy from FFT magnitude bins.
 * Bin resolution = SAMPLE_RATE / 1024.
 * Bass:   bins 0 to 37, covers low-frequency content
 * Mid:    bins 38 to 256, covers the middle of the spectrum
 * Treble: bins 257 to 511, covers the upper half of the spectrum
 * Each band is normalized to 0 to 100.
 */
void band_extract(void) {
  unsigned int bass_sum = 0, mid_sum = 0, treble_sum = 0;
  int k;

  for (k = 0; k <= 37; k++) {
    bass_sum += fft_mag[k];
  }
  for (k = 38; k <= 256; k++) {
    mid_sum += fft_mag[k];
  }
  for (k = 257; k < FFT_HALF; k++) {
    treble_sum += fft_mag[k];
  }

  /* Use sqrt compression so audible playback does not peg the meters. */
  bass_energy = compress_fft_sum(bass_sum, 3, 100);
  mid_energy = compress_fft_sum(mid_sum, 4, 100);
  treble_energy = compress_fft_sum(treble_sum, 4, 100);
}

/* BPM Detection Functions */

/*
 * Beat detection using per-hop energy and a simple adaptive threshold.
 *
 * For each 64-sample hop, compute the average absolute sample value.
 * Track a slow EMA baseline. If the hop energy exceeds baseline times sensitivity
 * and enough hops have passed since the last beat (refractory period), record
 * a beat and update the running-average interval.
 */
void beat_detect(void) {
  int hop, i;

  for (hop = 0; hop < BUFFER_SIZE; hop += BPM_HOP_SIZE) {
    int sum = 0;
    for (i = 0; i < BPM_HOP_SIZE; i++) {
      sum += iabs32(sample_buf[hop + i]);
    }
    int hop_energy = sum / BPM_HOP_SIZE;

    bpm_envelope += (hop_energy - bpm_envelope) >> 4; /* slow baseline EMA */

    int threshold = (bpm_envelope * sensitivity) / 100 + 1;
    int gap = bpm_hop_counter - bpm_last_beat_hop;

    if (hop_energy > threshold && gap >= BPM_PEAK_MIN_GAP_HOPS) {
      beat_flag = 1;
      if (bpm_last_beat_hop >= 0) {
        if (bpm_avg_interval == 0) {
          bpm_avg_interval = gap;
        } else {
          bpm_avg_interval = (bpm_avg_interval * 3 + gap + 2) >> 2;
        }
      }
      bpm_last_beat_hop = bpm_hop_counter;
    }
    bpm_hop_counter++;
  }
}

/*
 * Convert the running-average beat interval to a BPM display value.
 * Clears BPM if no beat has arrived in a long time.
 */
void bpm_update(void) {
  if (bpm_last_beat_hop < 0 ||
      (bpm_hop_counter - bpm_last_beat_hop) > BPM_MAX_INTERVAL_HOPS * 2) {
    bpm = 0;
    bpm_avg_interval = 0;
    return;
  }

  if (bpm_avg_interval > 0) {
    long long samples_per_beat = (long long)bpm_avg_interval * BPM_HOP_SIZE;
    int raw = (int)(BPM_SAMPLES_PER_MINUTE / samples_per_beat);
    while (raw < BPM_MIN) {
      raw <<= 1;
    }
    while (raw > BPM_MAX) {
      raw = (raw + 1) >> 1;
    }
    if (raw >= BPM_MIN && raw <= BPM_MAX) {
      bpm = raw;
    }
  }
}

/*
 * Smooth display values: instant attack, slow decay at 75% per frame.
 * Eliminates flicker from beat pulses while keeping responsiveness to new peaks.
 */
void smooth_display(void) {
  int b, j, height, start_bin;
  unsigned int sum;

  /* Smooth spectrum bar heights */
  for (b = 0; b < NUM_BARS; b++) {
    sum = 0;
    start_bin = b * BINS_PER_BAR;
    for (j = 0; j < BINS_PER_BAR; j++) {
      if (start_bin + j < FFT_HALF) {
        sum += fft_mag[start_bin + j];
      }
    }
    height = compress_fft_sum(sum, 0, 200);

    if (height >= smooth_bars[b]) {
      smooth_bars[b] = height; /* instant attack */
    } else {
      smooth_bars[b] = (smooth_bars[b] * 3) >> 2; /* 75% decay */
      if (smooth_bars[b] < height) {
        smooth_bars[b] = height;
      }
    }
  }

  /* Smooth band energies */
  if (bass_energy >= disp_bass) {
    disp_bass = bass_energy;
  } else {
    disp_bass = (disp_bass * 3) >> 2;
  }
  if (mid_energy >= disp_mid) {
    disp_mid = mid_energy;
  } else {
    disp_mid = (disp_mid * 3) >> 2;
  }
  if (treble_energy >= disp_treble) {
    disp_treble = treble_energy;
  } else {
    disp_treble = (disp_treble * 3) >> 2;
  }
}

/* Apply gentle decay each VSync frame when there is no new FFT data.
 * Uses 7/8 retention, which is slightly softer than the 3/4 in smooth_display. */
void decay_display(void) {
  for (int b = 0; b < NUM_BARS; b++) {
    smooth_bars[b] = (smooth_bars[b] * 7) >> 3;
  }
  disp_bass = (disp_bass * 7) >> 3;
  disp_mid = (disp_mid * 7) >> 3;
  disp_treble = (disp_treble * 7) >> 3;
}

/* Update the mood classification using a slow EMA and hysteresis.
 * A new mood must hold steady for MOOD_SWITCH_FRAMES cycles before it sticks. */
void update_mood(void) {
  /* Slow EMA update, converges toward input times 128 */
  mood_bass_acc   += disp_bass   - (mood_bass_acc   >> 7);
  mood_mid_acc    += disp_mid    - (mood_mid_acc    >> 7);
  mood_treble_acc += disp_treble - (mood_treble_acc >> 7);
  mood_energy_acc += energy_level - (mood_energy_acc >> 7);

  /* Read back smoothed values */
  int smooth_bass   = mood_bass_acc   >> 7;
  int smooth_mid    = mood_mid_acc    >> 7;
  int smooth_treble = mood_treble_acc >> 7;
  int smooth_energy = mood_energy_acc >> 7;

  /* Classify mood from smoothed values */
  int dom_bass = (smooth_bass >= smooth_mid) && (smooth_bass >= smooth_treble);
  int dom_mid  = (smooth_mid > smooth_bass)  && (smooth_mid >= smooth_treble);

  int suggested;
  if ((dom_bass && smooth_energy > 50) || bpm > 140) {
    suggested = 0; /* INTENSE */
  } else if (dom_mid || bpm > 100) {
    suggested = 1; /* GROOVY */
  } else {
    suggested = 2; /* CHILL */
  }

  /* Hysteresis: only switch after sustained agreement on a new mood */
  if (suggested == current_mood) {
    /* Already on the right mood, reset the counter */
    mood_candidate_count = 0;
  } else if (suggested == mood_candidate) {
    /* Same candidate as before, keep counting */
    mood_candidate_count++;
    if (mood_candidate_count >= MOOD_SWITCH_FRAMES) {
      current_mood = suggested;
      mood_candidate_count = 0;
    }
  } else {
    /* New candidate appeared, restart the count */
    mood_candidate = suggested;
    mood_candidate_count = 1;
  }
}

/* VGA Functions */

/* Write a single pixel to the VGA back buffer (RGB565, 320x240) */
void plot_pixel(int x, int y, short color) {
  if (x < 0 || x >= SCREEN_W || y < 0 || y >= SCREEN_H) {
    return;
  }
  /* VGA pixel buffer stride is 512 pixels (1024 bytes) per row */
  back_buf_ptr[y * 512 + x] = color;
}

/* Clear the entire back buffer to black.
 * Uses 32-bit writes (2 pixels at a time) for roughly 2x speedup. */
void clear_screen(void) {
  volatile int *p = (volatile int *)back_buf_ptr;
  int total = 512 * 240 / 2; /* 61440 int-sized writes */
  for (int i = 0; i < total; i++) {
    p[i] = 0;
  }
}

/* Draw a filled rectangle on the back buffer */
void draw_rect_fill(int x0, int y0, int w, int h, short color) {
  for (int y = y0; y < y0 + h && y < SCREEN_H; y++) {
    if (y < 0) {
      continue;
    }
    for (int x = x0; x < x0 + w && x < SCREEN_W; x++) {
      if (x < 0) {
        continue;
      }
      back_buf_ptr[y * 512 + x] = color;
    }
  }
}

/* Draw a horizontal line */
void draw_hline(int x1, int x2, int y, short color) {
  if (y < 0 || y >= SCREEN_H) {
    return;
  }
  if (x1 < 0) {
    x1 = 0;
  }
  if (x2 >= SCREEN_W) {
    x2 = SCREEN_W - 1;
  }
  for (int x = x1; x <= x2; x++) {
    back_buf_ptr[y * 512 + x] = color;
  }
}

/*
 * Trigger a VGA buffer swap and wait for VSync.
 * After return, back_buf_ptr points to the new back buffer.
 */
void wait_for_vsync(void) {
  volatile struct pixel_buf_ctrl_t *ctrl =
      (struct pixel_buf_ctrl_t *)PIXEL_BUF_CTRL_BASE;

  /* Initiate buffer swap by writing 1 to the buffer register */
  ctrl->buffer = 1;

  /* Wait until the swap completes (status bit 0 clears) */
  while (ctrl->status & 0x01) { }

  /* Update back buffer pointer to the new back buffer */
  back_buf_ptr = (volatile short *)(ctrl->back_buffer);
}

void vga_poll_swap(void) {
  if (!vga_swap_pending) {
    return;
  }

  volatile struct pixel_buf_ctrl_t *ctrl =
      (struct pixel_buf_ctrl_t *)PIXEL_BUF_CTRL_BASE;

  if ((ctrl->status & 0x01) == 0) {
    back_buf_ptr = (volatile short *)(ctrl->back_buffer);
    vga_swap_pending = 0;
  }
}

void vga_present(void) {
  volatile struct pixel_buf_ctrl_t *ctrl =
      (struct pixel_buf_ctrl_t *)PIXEL_BUF_CTRL_BASE;

  if (vga_swap_pending) {
    return;
  }

  ctrl->buffer = 1;
  vga_swap_pending = 1;
}

/* Set up VGA double-buffering so we always draw to an off-screen buffer.
 * By default both registers point to the same address, which causes flicker. */
void vga_init(void) {
  volatile struct pixel_buf_ctrl_t *ctrl =
      (struct pixel_buf_ctrl_t *)PIXEL_BUF_CTRL_BASE;

  /* Point back buffer to our SDRAM array (distinct from 0xC8000000) */
  ctrl->back_buffer = (unsigned int)pixel_buf_back;

  /* Clear the back buffer (pixel_buf_back, not displayed) */
  back_buf_ptr = (volatile short *)pixel_buf_back;
  clear_screen();

  /* Swap: pixel_buf_back becomes the front, 0xC8000000 becomes the back */
  wait_for_vsync();

  /* Clear the new back buffer (0xC8000000, not displayed) */
  clear_screen();
}

/* Returns a VGA color for the current mood.
 * Intense (bass heavy, high energy) = red/orange
 * Groovy (mid dominant) = green/yellow
 * Chill (treble or quiet) = blue/purple */
short get_mood_color(void) {
  /* Use the smoothed energy for color intensity */
  int smooth_energy = mood_energy_acc >> 7;
  if (smooth_energy > 100) {
    smooth_energy = 100;
  }

  int r, g, b;

  if (current_mood == 0) {
    /* Intense: red-orange tones */
    r = 20 + (smooth_energy * 11) / 100;
    g = 10 + (smooth_energy * 20) / 100;
    b = 0;
  } else if (current_mood == 1) {
    /* Groovy: green-yellow tones */
    r = 8 + (smooth_energy * 10) / 100;
    g = 32 + (smooth_energy * 31) / 100;
    b = 0;
  } else {
    /* Chill: blue-purple tones */
    r = 4 + (smooth_energy * 8) / 100;
    g = 0;
    b = 16 + (smooth_energy * 15) / 100;
  }

  if (r > 31) {
    r = 31;
  }
  if (g > 63) {
    g = 63;
  }
  if (b > 31) {
    b = 31;
  }

  return RGB565(r, g, b);
}

/* VGA Character Buffer Functions (80 cols x 60 rows, base 0x09000000) */
#define CHAR_BUF_BASE 0x09000000
#define CHAR_COLS 80
#define CHAR_ROWS 60

/* Write a single character at column x, row y */
void char_buf_write_char(int x, int y, char c) {
  if (x < 0 || x >= CHAR_COLS || y < 0 || y >= CHAR_ROWS) {
    return;
  }
  volatile char *cbuf = (volatile char *)CHAR_BUF_BASE;
  cbuf[(y << 7) + x] = c;
}

/* Write a null-terminated string starting at (x, y) */
void char_buf_print(int x, int y, const char *str) {
  while (*str && x < CHAR_COLS) {
    char_buf_write_char(x, y, *str);
    x++;
    str++;
  }
}

/* Write an integer (0-999) as 3 digits at (x, y) */
void char_buf_print_int(int x, int y, int val) {
  if (val < 0) {
    val = 0;
  }
  if (val > 999) {
    val = 999;
  }
  char digits[4];
  digits[0] = '0' + (val / 100) % 10;
  digits[1] = '0' + (val / 10) % 10;
  digits[2] = '0' + val % 10;
  digits[3] = '\0';
  char_buf_print(x, y, digits);
}

/* Clear the entire character buffer */
void char_buf_clear(void) {
  volatile char *cbuf = (volatile char *)CHAR_BUF_BASE;
  for (int i = 0; i < CHAR_ROWS << 7; i++) {
    cbuf[i] = ' ';
  }
}

/* Visual Mode Renderers */

/* Mode 1: Spectrum Visualizer
 * 32 bars representing FFT frequency bins, colored red to green to blue.
 * Peak-hold dots fall slowly and the border flashes on each beat. */
void draw_spectrum(void) {
  int bar_bottom = 220;
  int bar_width = 8;
  int bar_spacing = 10; /* 8px bar + 2px gap = 10px per bar, 32*10=320 */

  for (int b = 0; b < NUM_BARS; b++) {
    /* Read pre-smoothed bar height (computed in smooth_display) */
    int height = smooth_bars[b];

    /* Color gradient based on bar position */
    short color;
    if (b < 8) {
      /* Bass region: red with intensity gradient */
      int intensity = 16 + b * 2;
      if (intensity > 31) {
        intensity = 31;
      }
      color = RGB565(intensity, 0, 0);
    } else if (b < 20) {
      /* Mid region: green with intensity gradient */
      int intensity = 20 + (b - 8) * 3;
      if (intensity > 63) {
        intensity = 63;
      }
      color = RGB565(0, intensity, 0);
    } else {
      /* Treble region: blue with intensity gradient */
      int intensity = 12 + (b - 20) * 2;
      if (intensity > 31) {
        intensity = 31;
      }
      color = RGB565(0, 0, intensity);
    }

    /* Draw filled bar from bottom upward */
    int x0 = b * bar_spacing;
    if (height > 0) {
      draw_rect_fill(x0, bar_bottom - height, bar_width, height, color);
    }

    /* Peak-hold dot logic */
    if (height > peak_heights[b]) {
      peak_heights[b] = height;
      peak_timers[b] = 15; /* hold for 15 frames before falling */
    } else {
      if (peak_timers[b] > 0) {
        peak_timers[b]--;
      } else if (peak_heights[b] > 0) {
        peak_heights[b] -= 2; /* fall speed */
        if (peak_heights[b] < 0) {
          peak_heights[b] = 0;
        }
      }
    }

    /* Draw peak-hold dot (white horizontal line at peak) */
    if (peak_heights[b] > 0) {
      int peak_y = bar_bottom - peak_heights[b];
      if (peak_y >= 0 && peak_y < SCREEN_H) {
        draw_hline(x0, x0 + bar_width - 1, peak_y, RGB565(31, 63, 31));
      }
    }
  }

  /* Beat flash: draw white border around the display area */
  if (beat_flag) {
    draw_hline(0, SCREEN_W - 1, 0, RGB565(31, 63, 31));
    draw_hline(0, SCREEN_W - 1, SCREEN_H - 1, RGB565(31, 63, 31));
    for (int y = 0; y < SCREEN_H; y++) {
      plot_pixel(0, y, RGB565(31, 63, 31));
      plot_pixel(SCREEN_W - 1, y, RGB565(31, 63, 31));
    }
  }
}

/* Mode 2: Bar Graph
 * Three large bars for bass, mid, and treble energy.
 * Color goes from green to yellow to red with energy level. */
void draw_bar_graph(void) {
  int bar_bottom = 220;
  int max_height = 200;
  int bar_width = 80;
  int bar_x[3] = {20, 120, 220};
  int values[3] = {disp_bass, disp_mid, disp_treble};

  for (int i = 0; i < 3; i++) {
    int height = values[i] * 2; /* 0-100 mapped to 0-200 pixels */
    if (height > max_height) {
      height = max_height;
    }

    /* Color based on energy level */
    short color;
    if (beat_flag) {
      color = RGB565(31, 63, 31); /* white flash on beat */
    } else if (values[i] >= 66) {
      color = RGB565(31, 0, 0); /* red = high energy */
    } else if (values[i] >= 33) {
      color = RGB565(31, 63, 0); /* yellow = medium */
    } else {
      color = RGB565(0, 63, 0); /* green = low */
    }

    if (height > 0) {
      draw_rect_fill(bar_x[i], bar_bottom - height, bar_width, height, color);
    }

    /* Label bars with a colored marker at the bottom */
    short label_color = RGB565(31, 63, 31); /* default white */
    if (i == 0) {
      label_color = RGB565(31, 0, 0); /* bass = red */
    } else if (i == 1) {
      label_color = RGB565(0, 63, 0); /* mid = green */
    } else if (i == 2) {
      label_color = RGB565(0, 0, 31); /* treble = blue */
    }
    draw_rect_fill(bar_x[i], bar_bottom + 2, bar_width, 4, label_color);
  }
}

/*
 * Mode 3: Waveform (Oscilloscope)
 * Draws raw audio samples as a connected waveform across the screen.
 * Color tinted by mood (warm for high energy, cool for low).
 */
void draw_waveform(void) {
  short color = get_mood_color();
  int center_y = SCREEN_H / 2;
  int prev_y = center_y;

  for (int x = 0; x < SCREEN_W; x++) {
    /* Map screen x to sample buffer index */
    int sample_idx = (x * BUFFER_SIZE) / SCREEN_W;
    int s = sample_buf[sample_idx] >> 16; /* reduce to ~8-bit range */

    /* Scale to screen: center +/- 100 pixels */
    int y = center_y - (s * 100) / 128;
    if (y < 0) {
      y = 0;
    }
    if (y >= SCREEN_H) {
      y = SCREEN_H - 1;
    }

    /* Draw vertical segment connecting adjacent sample points */
    int y_start = prev_y < y ? prev_y : y;
    int y_end = prev_y > y ? prev_y : y;
    for (int dy = y_start; dy <= y_end; dy++) {
      plot_pixel(x, dy, color);
    }

    prev_y = y;
  }

  /* Dim center reference line (zero crossing) */
  draw_hline(0, SCREEN_W - 1, center_y, RGB565(8, 16, 8));

  /* Beat flash border */
  if (beat_flag) {
    draw_hline(0, SCREEN_W - 1, 0, RGB565(31, 63, 31));
    draw_hline(0, SCREEN_W - 1, SCREEN_H - 1, RGB565(31, 63, 31));
  }
}

/* Initialize particle positions and velocities with pseudo-random values */
void init_particles(void) {
  for (int i = 0; i < NUM_PARTICLES; i++) {
    particles[i].x = (int)(simple_rand() % SCREEN_W) << 8;
    particles[i].y = (int)(simple_rand() % SCREEN_H) << 8;
    particles[i].dx = (int)(simple_rand() % 512) - 256;
    particles[i].dy = (int)(simple_rand() % 512) - 256;
  }
  particles_init = 1;
}

/*
 * Mode 4: Mood Screen
 * Full-screen color wash based on energy and frequency balance.
 * Particles drift with energy-proportional velocity.
 * Text overlay shows BPM and energy stats via character buffer.
 */
void draw_mood_screen(void) {
  if (!particles_init) {
    init_particles();
  }

  /* Determine mood base color and extract RGB components */
  short bg_color = get_mood_color();
  int r = (bg_color >> 11) & 0x1F;
  int g = (bg_color >> 5) & 0x3F;
  int b = bg_color & 0x1F;

  /* Vertical gradient from 40% brightness at the top to 100% at the bottom */
  for (int y = 0; y < SCREEN_H; y++) {
    int scale = 40 + (y * 60) / SCREEN_H;
    int scaled_r = (r * scale) / 100;
    int scaled_g = (g * scale) / 100;
    int scaled_b = (b * scale) / 100;
    if (scaled_r > 31) {
      scaled_r = 31;
    }
    if (scaled_g > 63) {
      scaled_g = 63;
    }
    if (scaled_b > 31) {
      scaled_b = 31;
    }
    short row_color = RGB565(scaled_r, scaled_g, scaled_b);
    for (int x = 0; x < SCREEN_W; x++) {
      back_buf_ptr[y * 512 + x] = row_color;
    }
  }

  /* Update and draw particles */
  int speed_scale = 1 + energy_level / 10; /* 1-11 */
  for (int i = 0; i < NUM_PARTICLES; i++) {
    particles[i].x += (particles[i].dx * speed_scale) >> 3;
    particles[i].y += (particles[i].dy * speed_scale) >> 3;

    /* Wrap around screen edges */
    if (particles[i].x < 0) {
      particles[i].x += SCREEN_W << 8;
    }
    if (particles[i].x >= SCREEN_W << 8) {
      particles[i].x -= SCREEN_W << 8;
    }
    if (particles[i].y < 0) {
      particles[i].y += SCREEN_H << 8;
    }
    if (particles[i].y >= SCREEN_H << 8) {
      particles[i].y -= SCREEN_H << 8;
    }

    /* Draw 3x3 bright white particle */
    int px = particles[i].x >> 8;
    int py = particles[i].y >> 8;
    for (int dy = -1; dy <= 1; dy++) {
      for (int dx = -1; dx <= 1; dx++) {
        plot_pixel(px + dx, py + dy, RGB565(31, 63, 31));
      }
    }
  }

  /* Beat flash: double bright border */
  if (beat_flag) {
    draw_hline(0, SCREEN_W - 1, 0, RGB565(31, 63, 31));
    draw_hline(0, SCREEN_W - 1, 1, RGB565(31, 63, 31));
    draw_hline(0, SCREEN_W - 1, SCREEN_H - 1, RGB565(31, 63, 31));
    draw_hline(0, SCREEN_W - 1, SCREEN_H - 2, RGB565(31, 63, 31));
  }

  /* Text overlay via character buffer */
  char_buf_print(30, 2, "MOOD SCREEN");

  char_buf_print(2, 5, "BPM: ");
  char_buf_print_int(7, 5, bpm);

  char_buf_print(2, 7, "ENERGY: ");
  char_buf_print_int(10, 7, energy_level);

  char_buf_print(2, 9, "BASS:   ");
  char_buf_print_int(10, 9, disp_bass);
  char_buf_print(2, 10, "MID:    ");
  char_buf_print_int(10, 10, disp_mid);
  char_buf_print(2, 11, "TREBLE: ");
  char_buf_print_int(10, 11, disp_treble);

  /* Mood label from the stable current_mood classification */
  char_buf_print(2, 13, "MOOD: ");
  if (current_mood == 0) {
    char_buf_print(8, 13, "INTENSE ");
  } else if (current_mood == 1) {
    char_buf_print(8, 13, "GROOVY  ");
  } else {
    char_buf_print(8, 13, "CHILL   ");
  }
}

/* PS/2 Keyboard Input */

/* PS/2 scan code state machine */
static int ps2_break_flag = 0;    /* next code is a break (key release) */
static int ps2_extended_flag = 0; /* next code is an extended key */

/*
 * Poll PS/2 keyboard for a scan code.
 * Returns the scan code if data is valid, -1 otherwise.
 */
int read_ps2_key(void) {
  volatile int *ps2_ptr = (int *)PS2_BASE;
  int data = *ps2_ptr;
  if (data & 0x8000) { /* RVALID bit 15 */
    return data & 0xFF;
  }
  return -1;
}

/*
 * Handle PS/2 scan code with state machine for break/extended prefixes.
 * Controls: 1-4 = mode switch, Up/Down = sensitivity, Space = pause.
 */
void handle_key(int code) {
  /* Break prefix: next code is a key release, ignore it */
  if (code == 0xF0) {
    ps2_break_flag = 1;
    return;
  }

  /* Extended key prefix (arrow keys, etc.) */
  if (code == 0xE0) {
    ps2_extended_flag = 1;
    return;
  }

  /* If this is a break code, just clear the flag and ignore */
  if (ps2_break_flag) {
    ps2_break_flag = 0;
    ps2_extended_flag = 0;
    return;
  }

  /* Handle extended keys (arrow keys) */
  if (ps2_extended_flag) {
    ps2_extended_flag = 0;
    if (code == 0x75) { /* Up arrow */
      sensitivity += 10;
      if (sensitivity > 300) {
        sensitivity = 300;
      }
      render_requested = 1;
    } else if (code == 0x72) { /* Down arrow */
      sensitivity -= 10;
      if (sensitivity < 110) {
        sensitivity = 110;
      }
      render_requested = 1;
    }
    return;
  }

  /* Regular make codes */
  switch (code) {
    case 0x16: current_mode = MODE_SPECTRUM; render_requested = 1; break; /* key '1' */
    case 0x1E: current_mode = MODE_BARS;     render_requested = 1; break; /* key '2' */
    case 0x26: current_mode = MODE_WAVEFORM; render_requested = 1; break; /* key '3' */
    case 0x25: current_mode = MODE_MOOD;     render_requested = 1; break; /* key '4' */
    case 0x29: paused = !paused;             render_requested = 1; break; /* space */
    case 0x2D:                                                             /* key 'R' */
      bpm_reset_state();
      for (int i = 0; i < NUM_BARS; i++) {
        smooth_bars[i] = 0;
        peak_heights[i] = 0;
        peak_timers[i] = 0;
      }
      disp_bass = 0;
      disp_mid = 0;
      disp_treble = 0;
      mood_bass_acc = 0;
      mood_mid_acc = 0;
      mood_treble_acc = 0;
      mood_energy_acc = 0;
      current_mood = 2;
      mood_candidate = 2;
      mood_candidate_count = 0;
      render_requested = 1;
      break;
    default: break;
  }
}

/* Synthetic Test Signal Generator
 *
 * Controlled by DE1-SoC slide switches at 0xFF200040.
 * SW0 = 0: normal mode, reads real audio from the codec
 * SW0 = 1: test mode, fills sample_buf with a synthetic signal
 *
 * Test signal selection (SW2, SW1):
 *   0, 0 = single tone at 440 Hz (bass)
 *   0, 1 = dual tone at 220 Hz and 3520 Hz (bass and treble)
 *   1, 0 = beat pulse at 120 BPM
 *   1, 1 = frequency sweep from bass to treble
 */

/* Phase accumulators for test signal oscillators */
static int test_phase_a = 0;   /* primary oscillator */
static int test_phase_b = 0;   /* secondary oscillator (dual-tone / sweep) */
static int test_beat_ctr = 0;  /* sample counter for beat pulse envelope */
static int test_sweep_bin = 0; /* current sweep bin (0 to FFT_HALF-1) */

/*
 * Fill sample_buf[0..BUFFER_SIZE-1] with a synthetic test signal
 * based on SW1 and SW2 state. Amplitudes are chosen to produce
 * a moderate energy reading on the HEX display.
 *
 * Sine approximation: uses twiddle_cos table (1024 entries over
 * one full cycle at 8 kHz, index step = freq * 1024 / 8000).
 */
void fill_test_signal(int sw1, int sw2) {
  int i;

  if (!sw2 && !sw1) {
    /* Single tone at 440 Hz, index step 56, amplitude 0x80 (low energy) */
    for (i = 0; i < BUFFER_SIZE; i++) {
      test_phase_a = (test_phase_a + 56) & 1023;
      int s =
          twiddle_cos[test_phase_a < 512 ? test_phase_a : 1023 - test_phase_a];
      sample_buf[i] = s * 0x80;
    }

  } else if (!sw2 && sw1) {
    /* Dual tone: 220 Hz (step 28) and 3520 Hz (step 451), amplitude 0x80 */
    for (i = 0; i < BUFFER_SIZE; i++) {
      test_phase_a = (test_phase_a + 28) & 1023;
      test_phase_b = (test_phase_b + 451) & 1023;
      int idx_a = test_phase_a < 512 ? test_phase_a : 1023 - test_phase_a;
      int idx_b = test_phase_b < 512 ? test_phase_b : 1023 - test_phase_b;
      int s = (twiddle_cos[idx_a] + twiddle_cos[idx_b]) / 2;
      sample_buf[i] = s * 0x80;
    }

  } else if (sw2 && !sw1) {
    /* Beat pulse at 120 BPM, kick burst every 4000 samples, amplitude 0x500 */
    int beat_period = 4000; /* samples per beat at 120 BPM */
    int burst_len = 50;     /* samples in the kick burst */
    int kick_step = 102;    /* ~100 Hz sine step */
    for (i = 0; i < BUFFER_SIZE; i++) {
      int phase_in_beat = test_beat_ctr % beat_period;
      int s;
      if (phase_in_beat < burst_len) {
        /* Decaying sine burst */
        test_phase_a = (test_phase_a + kick_step) & 1023;
        int idx = test_phase_a < 512 ? test_phase_a : 1023 - test_phase_a;
        /* Linear decay from full amplitude to zero over burst_len samples */
        int env = (burst_len - phase_in_beat) * (0x4000 / burst_len);
        s = (twiddle_cos[idx] * env) >> 14;
        s = s * 0x500;
      } else {
        s = 0;
      }
      sample_buf[i] = s;
      test_beat_ctr++;
    }

  } else {
    /* Frequency sweep, advances one bin per buffer, amplitude 0x300 */
    int step = test_sweep_bin + 1; /* step 1 to 512 */
    for (i = 0; i < BUFFER_SIZE; i++) {
      test_phase_a = (test_phase_a + step) & 1023;
      int idx = test_phase_a < 512 ? test_phase_a : 1023 - test_phase_a;
      sample_buf[i] = twiddle_cos[idx] * 0x300;
    }
    /* Advance sweep bin */
    test_sweep_bin++;
    if (test_sweep_bin >= FFT_HALF) {
      test_sweep_bin = 0;
    }
  }
}

/* Main Loop */

int main(void) {
  struct audio_t *audio_ptr = (struct audio_t *)AUDIO_BASE;
  volatile int *sw_ptr = (int *)SW_BASE;
  int i;

  /* Force the codec onto line-in so the pipeline never uses the microphone. */
  audio_select_line_in();

  /* Initialize audio port after switching the input source */
  audio_ptr->control = 0xC; /* clear FIFOs */
  audio_ptr->control = 0x0;

  /* Initialize VGA double-buffered display */
  vga_init();
  init_fft_window();

  /* Clear all displays */
  hex_show_full(0, current_mode, 0);
  led_bar(0);

  /* Initialize peak-hold, smoothing, and BPM state */
  for (i = 0; i < NUM_BARS; i++) {
    peak_heights[i] = 0;
    peak_timers[i] = 0;
    smooth_bars[i] = 0;
  }
  bpm_reset_state();

  buf_index = 0;

  while (1) {
    vga_poll_swap();

    /* Drain PS/2 keyboard FIFO and process any pending scan codes */
    {
      int key;
      while ((key = read_ps2_key()) >= 0) {
        handle_key(key);
      }
    }

    /* Read slide switches:
     *   SW0 = test mode enable
     *   SW1 = signal select bit 0
     *   SW2 = signal select bit 1 */
    int sw = *sw_ptr;
    int test_mode = sw & 0x1;
    int sw1 = (sw >> 1) & 0x1;
    int sw2 = (sw >> 2) & 0x1;

    /* PHASE 1: Collect audio / generate test signal */
    new_data_ready = 0;

    if (test_mode) {
      /* Test mode: fill the buffer with the chosen test signal */
      fill_test_signal(sw1, sw2);
      new_data_ready = 1;
    } else {
      /* Normal mode: drain the input FIFO continuously.
       * Playback goes through the codec directly, so the CPU
       * only needs to handle capture and analysis. */
      while ((audio_ptr->rarc > 0) && (audio_ptr->ralc > 0)) {
        int left = audio_ptr->ldata;
        int right = audio_ptr->rdata;
        int mono = (left >> 1) + (right >> 1);

        /* Store a mono mix so both channels contribute to the FFT. */
        sample_buf[buf_index] = mono;
        buf_index++;

        if (buf_index >= BUFFER_SIZE) {
          buf_index = 0;
          new_data_ready = 1;
          break; /* process this buffer before collecting more */
        }
      }
    }

    /* PHASE 2: Run analysis (only when new data) */
    if (new_data_ready && !paused) {
      {
        int raw_energy = compute_energy(sample_buf, BUFFER_SIZE);
        energy_smooth = smooth_energy_level(energy_smooth, raw_energy);
        energy_level = energy_smooth >> 8;
        if (energy_level > 100) {
          energy_level = 100;
        }
      }

      fft_compute(sample_buf);
      fft_magnitudes();
      band_extract();
      beat_detect();
      bpm_update();
      smooth_display();
      update_mood();
      render_requested = 1;

      hex_show_full(energy_level, current_mode, bpm);
      led_bar(energy_level);
    }

    /* PHASE 3: Render only when a fresh frame is needed */
    if (render_requested && !vga_swap_pending) {
      clear_screen();
      char_buf_clear();

      switch (current_mode) {
        case MODE_SPECTRUM:
          draw_spectrum();
          break;
        case MODE_BARS:
          draw_bar_graph();
          break;
        case MODE_WAVEFORM:
          draw_waveform();
          break;
        case MODE_MOOD:
          draw_mood_screen();
          break;
        default:
          draw_spectrum();
          break;
      }

      vga_present();
      render_requested = 0;
      beat_flag = 0;
    }
  }

  return 0;
}
