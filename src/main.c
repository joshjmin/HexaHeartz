int cosine_q15(int idx) {
  idx &= (FFT_SIZE - 1);
  if (idx == FFT_HALF) {
    return -32767;
  }
  if (idx < FFT_HALF) {
    return twiddle_cos[idx];
  }
  return twiddle_cos[FFT_SIZE - idx];
}

void init_fft_window(void) {
  for (int i = 0; i < FFT_SIZE; i++) {
    int c = cosine_q15(i);
    window_q15[i] = (short)((32767 - c) >> 1);
  }
}

int compute_dc_offset(int *samples, int count) {
  long long sum = 0;
  if (count <= 0) {
    return 0;
  }
  for (int i = 0; i < count; i++) {
    sum += samples[i];
  }
  return (int)(sum / count);
}

int compute_auto_shift(int *samples, int count, int dc_offset, int target_peak) {
  int peak = 0;

  if (target_peak <= 0) {
    return 0;
  }

  for (int i = 0; i < count; i++) {
    int centered = samples[i] - dc_offset;
    int abs_val = iabs32(centered);
    if (abs_val > peak) {
      peak = abs_val;
    }
  }

  int shift = 0;
  while (peak > target_peak) {
    peak >>= 1;
    shift++;
  }

  return shift;
}

int compress_fft_sum(unsigned int sum, int shift, int max_out) {
  if (sum <= FFT_SUM_FLOOR) {
    return 0;
  }

  sum -= FFT_SUM_FLOOR;
  if (shift > 0) {
    sum >>= shift;
  }

  int level = (int)isqrt_u64((unsigned long long)sum);
  if (level > max_out) {
    level = max_out;
  }
  return level;
}

