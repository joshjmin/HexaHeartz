/*
 * Convert RMS to a 0 to 100 scale using logarithmic mapping.
 * Uses integer log2 with linear interpolation between powers of 2.
 *
 * noise_floor_log2 sets the log2 value below which the result is 0.
 * full_scale_log2  sets the log2 value that maps to 100.
 */
int rms_to_db_scale(int rms, int noise_floor_log2, int full_scale_log2) {
  if (rms <= 0) {
    return 0;
  }

  /* Integer log2 */
  int log2_val = 0;
  int temp = rms;
  while (temp > 1) {
    temp >>= 1;
    log2_val++;
  }

  /* Linear interpolation for the fractional part (0 to 99) */
  int lower = 1 << log2_val;
  int frac_100 = ((rms - lower) * 100) / lower;

  /* log2 value scaled by 100 for precision */
  int log2_x100 = log2_val * 100 + frac_100;
  int floor_x100 = noise_floor_log2 * 100;
  int range_x100 = (full_scale_log2 - noise_floor_log2) * 100;

  if (log2_x100 <= floor_x100) {
    return 0;
  }

  int energy = ((log2_x100 - floor_x100) * 100) / range_x100;
  if (energy > 100) {
    energy = 100;
  }
  return energy;
}

/*
 * Compute energy (RMS) of the sample buffer and return a value from 0 to 100.
 * DC is removed but no auto-scaling is applied, so the result reflects true
 * input loudness. A fixed right-shift keeps detail in quiet passages while
 * leaving headroom for louder signals.
 *
 * After the shift, the practical RMS range is roughly:
 *   silence     = 0
 *   quiet music = 30 to 100  (log2 around 5 to 6)
 *   loud music  = 400 to 1200 (log2 around 8 to 10)
 *   very loud   = 2000 to 4000 (log2 around 11 to 12)
 *
 * We map log2 3 to 13 onto 0 to 100.
 */
#define ENERGY_FIXED_SHIFT 12
#define ENERGY_NOISE_FLOOR_LOG2 3
#define ENERGY_FULL_SCALE_LOG2  13
#define ENERGY_ATTACK_OLD_WEIGHT 5
#define ENERGY_ATTACK_NEW_WEIGHT 3
#define ENERGY_RELEASE_OLD_WEIGHT 1
#define ENERGY_RELEASE_NEW_WEIGHT 1

int compute_energy(int *samples, int count) {
  if (count <= 0) {
    return 0;
  }

  int dc_offset = compute_dc_offset(samples, count);
  unsigned long long sum_sq = 0;

  for (int i = 0; i < count; i++) {
    int s = (samples[i] - dc_offset) >> ENERGY_FIXED_SHIFT;
    sum_sq += (unsigned long long)((long long)s * (long long)s);
  }

  int rms = (int)isqrt_u64(sum_sq / (unsigned int)count);

  return rms_to_db_scale(rms, ENERGY_NOISE_FLOOR_LOG2,
                         ENERGY_FULL_SCALE_LOG2);
}

/*
 * Smooth the displayed energy with moderate attack and faster release.
 * Keeps the readout stable while still letting loud passages breathe.
 */
int smooth_energy_level(int current_fp, int raw_energy) {
  int target_fp = raw_energy << 8;

  if (target_fp >= current_fp) {
    return (current_fp * ENERGY_ATTACK_OLD_WEIGHT +
            target_fp * ENERGY_ATTACK_NEW_WEIGHT) >>
           3;
  }

  return (current_fp * ENERGY_RELEASE_OLD_WEIGHT +
          target_fp * ENERGY_RELEASE_NEW_WEIGHT) >>
         1;
}

