/* Hardware Register Structs */

/*
 * Audio port register layout (base 0xFF203040).
 * Offset +0: Control register
 * Offset +4: FIFOSPACE register (4 byte-sized FIFO counters)
 *   Note: On little-endian Nios V, byte order within the 32-bit FIFOSPACE
 *   word is reversed from the bit-field documentation. The check
 *   (rarc > 0 && ralc > 0 && wsrc > 0 && wslc > 0) works regardless of
 *   byte ordering since all four FIFO counters must be nonzero.
 * Offset +8: Left data
 * Offset +12: Right data
 */
struct audio_t {
  volatile unsigned int control;
  volatile unsigned char rarc;
  volatile unsigned char ralc;
  volatile unsigned char wsrc;
  volatile unsigned char wslc;
  volatile unsigned int ldata;
  volatile unsigned int rdata;
};

/* Audio/video configuration core used to program the WM8731 codec over I2C */
struct av_config_t {
  volatile unsigned int control;
  volatile unsigned int status;
  volatile unsigned int address;
  volatile unsigned int data;
};

/* VGA pixel buffer controller */
struct pixel_buf_ctrl_t {
  volatile unsigned int buffer;      /* front buffer addr, write 1 to swap */
  volatile unsigned int back_buffer; /* back buffer address */
  volatile unsigned int resolution;  /* resolution register */
  volatile unsigned int status;      /* bit 0 is set while a swap is pending */
};

