/* Integer square root (Newton's method) */
int isqrt(int n) {
  if (n <= 0) {
    return 0;
  }
  if (n == 1) {
    return 1;
  }
  int x = n;
  int y = (x + 1) / 2;
  while (y < x) {
    x = y;
    y = (x + n / x) / 2;
  }
  return x;
}

/* 64-bit integer square root */
unsigned int isqrt_u64(unsigned long long n) {
  unsigned long long bit = 1ULL << 62;
  unsigned long long root = 0;

  while (bit > n) {
    bit >>= 2;
  }

  while (bit != 0) {
    if (n >= root + bit) {
      n -= root + bit;
      root = (root >> 1) + bit;
    } else {
      root >>= 1;
    }
    bit >>= 2;
  }

  return (unsigned int)root;
}

