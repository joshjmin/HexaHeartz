/*
 * Wait until the audio/video config core is ready for the next transfer.
 * A timeout prevents the program from hanging if the peripheral stops responding.
 */
int av_config_wait_ready(struct av_config_t *av_config_ptr) {
  int timeout = AV_CONFIG_TIMEOUT;
  while (((av_config_ptr->status & AV_CONFIG_STATUS_RDY) == 0) &&
         (timeout > 0)) {
    timeout--;
  }
  return timeout > 0;
}

/*
 * Write a 9-bit WM8731 register through the DE1-SoC audio/video config core.
 * Returns 1 on success, 0 on timeout/NACK.
 */
int wm8731_write_reg(struct av_config_t *av_config_ptr, unsigned int reg,
                     unsigned int data) {
  if (!av_config_wait_ready(av_config_ptr)) {
    return 0;
  }

  av_config_ptr->address = reg & 0x7F;
  av_config_ptr->data = data & 0x1FF;

  if (!av_config_wait_ready(av_config_ptr)) {
    return 0;
  }

  if (av_config_ptr->status & AV_CONFIG_STATUS_ACK) {
    av_config_ptr->status = AV_CONFIG_STATUS_ACK; /* clear error flag */
    return 0;
  }

  return 1;
}

